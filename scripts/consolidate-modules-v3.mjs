import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const generatedPath = path.join(root, 'src/data/modules.generated.ts');
const consolidatedPath = path.join(root, 'knowledge/canonical/modules-v3-consolidated.json');
const checkOnly = process.argv.includes('--check');

const readGeneratedModules = () => {
  const source = fs.readFileSync(generatedPath, 'utf8');
  const prefix = 'export const MODULES_DATA = ';
  const start = source.indexOf(prefix);
  const end = source.lastIndexOf(' as ModuleData[];');
  if (start < 0 || end < 0) throw new Error('Formato inesperado de modules.generated.ts.');
  return JSON.parse(source.slice(start + prefix.length, end));
};

const sectionNumber = (title) => title.match(/^([A-Z]\.[0-9]+|[0-9]+(?:\.[0-9]+)?)\s+/)?.[1] || null;
const titleWords = (title) => new Set(
  title
    .replace(/^([A-Z]\.[0-9]+|[0-9]+(?:\.[0-9]+)?)\s+/, '')
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .toLowerCase().split(/[^a-z0-9]+/)
    .filter((word) => word.length > 3 && !['como', 'para', 'entre', 'pela', 'pelo', 'regra', 'regras'].includes(word))
);

const semanticallyRelated = (first, second) => {
  const a = titleWords(first.title);
  const b = titleWords(second.title);
  const overlap = [...a].filter((word) => b.has(word));
  return overlap.length >= 1 || first.title.toLowerCase() === second.title.toLowerCase();
};

const unique = (values = []) => [...new Set(values.filter(Boolean))];
const mergeSections = (first, second) => {
  const enriched = second.editorial || second.sourceConceptIds || second.limitsAndExceptions ? second : first;
  const original = enriched === second ? first : second;
  const contents = unique([original.contentMarkdown?.trim(), enriched.contentMarkdown?.trim()]);
  return {
    ...original,
    ...enriched,
    title: enriched.title,
    contentMarkdown: contents.join('\n\n---\n\n'),
    sourceConceptIds: unique([...(original.sourceConceptIds || []), ...(enriched.sourceConceptIds || [])]),
    limitsAndExceptions: unique([...(original.limitsAndExceptions || []), ...(enriched.limitsAndExceptions || [])]),
    contrasts: unique([...(original.contrasts || []), ...(enriched.contrasts || [])]),
    examTraps: unique([...(original.examTraps || []), ...(enriched.examTraps || [])]),
  };
};

const sortValue = (title) => {
  const key = sectionNumber(title);
  if (!key) return Number.MAX_SAFE_INTEGER;
  const numeric = key.replace(/^[A-Z]\./, '').split('.').map(Number);
  return (numeric[0] || 0) * 1000 + (numeric[1] || 0);
};

const consolidateModule = (module) => {
  const sections = [];
  const byNumber = new Map();
  const usedNumbers = new Set(module.sections.map((section) => sectionNumber(section.title)).filter(Boolean));
  const modulePrefix = String(module.id).match(/^mod([0-9]+)$/)?.[1];
  let nextSubsection = Math.max(0, ...[...usedNumbers]
    .filter((value) => modulePrefix && value.startsWith(`${modulePrefix}.`))
    .map((value) => Number(value.split('.')[1]) || 0)) + 1;

  for (const section of module.sections) {
    const number = sectionNumber(section.title);
    const previousIndex = number ? byNumber.get(number) : undefined;
    if (previousIndex === undefined) {
      if (number) byNumber.set(number, sections.length);
      sections.push(section);
      continue;
    }

    const previous = sections[previousIndex];
    if (semanticallyRelated(previous, section)) {
      sections[previousIndex] = mergeSections(previous, section);
      continue;
    }

    if (!modulePrefix) throw new Error(`Numeração conflitante sem rota segura: ${module.id} / ${section.title}`);
    while (usedNumbers.has(`${modulePrefix}.${nextSubsection}`)) nextSubsection += 1;
    const replacement = `${modulePrefix}.${nextSubsection}`;
    usedNumbers.add(replacement);
    nextSubsection += 1;
    sections.push({ ...section, title: section.title.replace(number, replacement) });
  }

  return { ...module, sections: sections.sort((a, b) => sortValue(a.title) - sortValue(b.title)) };
};

const modules = readGeneratedModules().map(consolidateModule);
const duplicateNumbers = modules.flatMap((module) => {
  const seen = new Set();
  return module.sections.flatMap((section) => {
    const number = sectionNumber(section.title);
    if (!number || !seen.has(number)) { if (number) seen.add(number); return []; }
    return [`${module.id}:${number}`];
  });
});
if (duplicateNumbers.length) throw new Error(`Seções duplicadas após consolidação: ${duplicateNumbers.join(', ')}`);

const artifact = {
  schemaVersion: '3.0.0',
  kind: 'suveca_consolidated_modules',
  policy: 'Uma seção canônica por número/conceito; ampliações V3 incorporadas sem apagar o texto válido anterior.',
  generatedAt: 'deterministic',
  modules,
};
const json = `${JSON.stringify(artifact, null, 2)}\n`;
const ts = `/* AUTO-GENERATED by scripts/consolidate-modules-v3.mjs. */\nimport type { ModuleData } from '../types/suveca';\n\nexport const MODULES_DATA = ${JSON.stringify(modules, null, 2)} as ModuleData[];\n`;

if (checkOnly) {
  if (!fs.existsSync(consolidatedPath) || fs.readFileSync(consolidatedPath, 'utf8') !== json) {
    throw new Error('modules-v3-consolidated.json está desatualizado. Execute npm run kb:modules:consolidate.');
  }
  if (fs.readFileSync(generatedPath, 'utf8') !== ts) {
    throw new Error('modules.generated.ts não corresponde à consolidação V3.');
  }
  console.log(`Consolidação V3 auditada: ${modules.length} módulos, ${modules.reduce((sum, module) => sum + module.sections.length, 0)} seções, 0 números duplicados.`);
} else {
  fs.writeFileSync(consolidatedPath, json);
  fs.writeFileSync(generatedPath, ts);
  console.log(`Consolidação V3 gravada: ${modules.length} módulos, ${modules.reduce((sum, module) => sum + module.sections.length, 0)} seções.`);
}
